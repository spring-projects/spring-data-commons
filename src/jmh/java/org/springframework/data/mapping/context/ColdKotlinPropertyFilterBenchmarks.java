package org.springframework.data.mapping.context;

import java.lang.reflect.Field;
import java.util.concurrent.TimeUnit;

import org.openjdk.jmh.annotations.Benchmark;
import org.openjdk.jmh.annotations.BenchmarkMode;
import org.openjdk.jmh.annotations.Fork;
import org.openjdk.jmh.annotations.Measurement;
import org.openjdk.jmh.annotations.Mode;
import org.openjdk.jmh.annotations.OutputTimeUnit;
import org.openjdk.jmh.annotations.Scope;
import org.openjdk.jmh.annotations.Setup;
import org.openjdk.jmh.annotations.State;
import org.openjdk.jmh.annotations.Warmup;

/**
 * Cold property filtering. A fresh fork keeps Kotlin metadata uninitialized for each measurement.
 *
 * @author Greg Taube
 */
@State(Scope.Thread)
@BenchmarkMode(Mode.SingleShotTime)
@OutputTimeUnit(TimeUnit.MILLISECONDS)
@Warmup(iterations = 0)
@Measurement(iterations = 1)
@Fork(10)
public class ColdKotlinPropertyFilterBenchmarks {

	private Field[] fields;

	@Setup
	public void setUp() {
		fields = SimpleDataClass.class.getDeclaredFields();
	}

	@Benchmark
	public int inspectOrdinaryProperties() {

		int included = 0;
		for (Field field : fields) {
			if (AbstractMappingContext.PersistentPropertyFilter.INSTANCE.matches(field)) {
				included++;
			}
		}
		return included;
	}
}
